const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch();
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:8765/islas/encuentro.html');
 await page.waitForFunction(()=>!document.querySelector('#sailing-start').disabled);
 assert.equal(await page.locator('.cast-member:visible').count(),1);
 assert.equal(await page.locator('#rescue-story').getAttribute('data-speaker'),'antonio');
 await page.waitForTimeout(250);
 const partial=await page.locator('#dialogue-line').textContent();
 assert(partial.length>1&&partial.length<80,'text is progressively revealed');
 await page.locator('#dialogue-next').click();
 assert.match(await page.locator('#dialogue-line').textContent(),/deriva/);
 await page.locator('#dialogue-next').click();
 assert.equal(await page.locator('#rescue-story').getAttribute('data-speaker'),'lucero');
 assert.equal(await page.locator('.cast-member:visible').count(),1);
 const sprite=await page.locator('.cast').boundingBox(), box=await page.locator('.story-dialogue').boundingBox();
 assert(Math.abs(sprite.x+sprite.width/2-box.x-box.width/2)<2,'Lucero is centered above the dialogue frame');
 await page.screenshot({path:'../../outputs/dialogo-lucero-movil-v2.png',fullPage:true});
 await page.locator('#dialogue-next').click();
 await page.locator('#dialogue-next').click();
 await page.locator('#dialogue-next').click();
 await page.locator('#sailing-start').click();
 await page.waitForTimeout(1300);
 await page.screenshot({path:'../../outputs/navegacion-restaurada-movil.png',fullPage:true});
 assert.match(await page.locator('.rescue-sea').evaluate(e=>getComputedStyle(e).backgroundImage),/ocean.webp/);
 assert.deepEqual(errors,[]);
 console.log('PASS sequential left/right actors, progressive text, tap to complete, start after dialogue and restored original sea');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
